// Bundles the browser viewer (renderer + runtime) into a string module that
// exporters embed into standalone HTML exhibits.
//
// npm pre-scripts call this before almost every command, so it skips the build
// when nothing the bundle reads has changed since the last run. The stamp lists
// every local source file esbuild read, plus the lockfile and this script.
// Pass --force to rebuild regardless.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';

const OUT = 'src/generated/standalone.ts';
const STAMP = 'src/generated/standalone.stamp.json';
const ALWAYS = ['package-lock.json', 'scripts/build-standalone.mjs'];

const hashFile = (file) => {
  try {
    return createHash('sha256').update(readFileSync(file)).digest('hex');
  } catch {
    return null;
  }
};

function upToDate() {
  if (process.argv.includes('--force') || !existsSync(OUT) || !existsSync(STAMP)) return false;
  try {
    const stamp = JSON.parse(readFileSync(STAMP, 'utf8'));
    const files = Object.entries(stamp.inputs ?? {});
    return files.length > 0 && files.every(([file, hash]) => hashFile(file) === hash);
  } catch {
    return false;
  }
}

if (upToDate()) {
  console.log('Standalone bundle: up to date');
} else {
  const result = await build({
    entryPoints: ['src/engine/standalone.ts'],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2022',
    write: false,
    minify: true,
    metafile: true,
    legalComments: 'inline',
    define: { 'process.env.NODE_ENV': '"production"' },
  });

  const js = result.outputFiles[0].text;
  if (!js.length) throw new Error('Empty standalone bundle');

  await mkdir('src/generated', { recursive: true });
  await writeFile(
    OUT,
    `// Generated by scripts/build-standalone.mjs. Do not edit.\nexport const standaloneBundle = ${JSON.stringify(js)};\n`,
  );

  // node_modules inputs are covered by the lockfile hash.
  const local = Object.keys(result.metafile.inputs).filter((file) => !file.includes('node_modules/'));
  const inputs = Object.fromEntries([...local, ...ALWAYS].map((file) => [file, hashFile(file)]));
  await writeFile(STAMP, `${JSON.stringify({ inputs }, null, 2)}\n`);
  console.log(`Standalone bundle: ${js.length} characters`);
}
