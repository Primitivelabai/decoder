// Bundles the browser viewer (renderer + runtime) into a string module that
// exporters embed into standalone HTML exhibits.
import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: ['src/engine/standalone.ts'],
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: 'es2022',
  write: false,
  minify: true,
  legalComments: 'inline',
  define: { 'process.env.NODE_ENV': '"production"' },
});

const js = result.outputFiles[0].text;
if (!js.length) throw new Error('Empty standalone bundle');

await mkdir('src/generated', { recursive: true });
await writeFile(
  'src/generated/standalone.ts',
  `// Generated by scripts/build-standalone.mjs. Do not edit.\nexport const standaloneBundle = ${JSON.stringify(js)};\n`,
);
console.log(`Standalone bundle: ${js.length} characters`);
